  # Normative sections that are not face families (meta/apparatus).
  MODEL_COVERAGE_NON_FACE = [
    "Status and precedence",
    "Mission and invariant",
    "Object model",
    "Performance: a declared, non-semantic channel",
  ].freeze

  MODEL_COVERAGE_ADAPTERS = %i[nokogiri oga rexml ox headed_ox libxml leptris].freeze

  module_function

  def families
    MODEL_COVERAGE_MATRIX.keys
  end

  def sections
    MODEL_COVERAGE_MATRIX.values.map { |cell| cell[:section] }.uniq
  end

  def pins_for(section)
    MODEL_COVERAGE_MATRIX.values.select { |cell| cell[:section] == section }
      .filter_map { |cell| cell[:pin] }.uniq.sort
  end

  def disposition(family, adapter)
    cell = MODEL_COVERAGE_MATRIX.fetch(family)
    if (id = (cell[:exempt] || {})[adapter])
      [:specd, id]
    elsif (error = (cell[:loud] || {})[adapter])
      [:loud, error]
    else
      [:equivalent, nil]
    end
  end

  def cell_text(family, adapter)
    kind, detail = disposition(family, adapter)
    case kind
    when :specd then detail
    when :loud then "loud (#{detail.split('::').last})"
    else "equivalent"
    end
  end

  # The published page block, deterministic (no clock, no engine
  # versions): the page is a view of the committed matrix and register,
  # so a data change without regeneration fails CI.
  def render_page_block
    lines = []
    lines << "Generated by `bundle exec rake docs:coverage` from the " \
             "coverage matrix and the divergence register. Do not edit " \
             "by hand: `spec/consistency/published_docs_spec.rb` fails " \
             "when this block is stale."
    lines << ""
    lines << %([cols="4#{',1' * MODEL_COVERAGE_ADAPTERS.size}",options="header"])
    lines << "|==="
    lines << "| Face family | " \
             "#{MODEL_COVERAGE_ADAPTERS.map { |adapter| adapter.to_s.tr('_', ' ') }.join(' | ')}"
    families.each do |family|
      lines << "| #{family} | " \
               "#{MODEL_COVERAGE_ADAPTERS.map { |adapter| cell_text(family, adapter) }.join(' | ')}"
    end
    lines << "|==="
    lines << ""
    lines << "*equivalent* — all adapters answer the same observable " \
             "result. *loud (...)* — the adapter raises the named error " \
             "for that face. *D-NN* — a registered divergence in " \
             "link:divergences.html[the register], with its rationale. " \
             "Every cell cites a pin; see the processing model's " \
             "`Pins::` line for the enforcing specs."
    lines.join("\n")
  end
